let ready;
function init() {
  if (!ready) ready = (async () => {
    try { await q(SCHEMA); } catch (e) { console.error('schema:', e.message); }
    if (!(await q1("SELECT 1 x FROM users WHERE role='owner'"))) {
      const u = process.env.OWNER_USER, p = process.env.OWNER_PASS;
      if (!u || !p) throw cfgErr('OWNER_USER dan OWNER_PASS');
      await q("INSERT INTO users(username,pass,role,created) SELECT $1::text,$2::text,'owner',$3::bigint WHERE NOT EXISTS (SELECT 1 FROM users WHERE role='owner') ON CONFLICT DO NOTHING", [clean(u, 24), hashPw(p), Date.now()]);
    }
  })().catch(e => { ready = null; throw e; });
  return ready;
}

