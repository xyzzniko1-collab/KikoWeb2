app.get('/auth/discord/callback', H(async (req, res) => {
  const st = readState(req.query.state, 'discord', req.viewer);
  if (!st) return res.status(400).send('Sesi verifikasi tidak valid atau kedaluwarsa. Ulangi dari halaman file.');
  if (!req.query.code) return back(res, st.linkId, 'fail');
  try {
    const tok = await postForm('https://discord.com/api/oauth2/token', {
      client_id: process.env.DISCORD_CLIENT_ID, client_secret: process.env.DISCORD_CLIENT_SECRET,
      grant_type: 'authorization_code', code: String(req.query.code), redirect_uri: baseUrl(req) + '/auth/discord/callback'
    });
    if (!tok.access_token) return back(res, st.linkId, 'err');
    const guilds = await (await fetch('https://discord.com/api/users/@me/guilds', { headers: { authorization: 'Bearer ' + tok.access_token } })).json();
    const r = await q1('SELECT * FROM reqs WHERE id=$1', [st.reqId]);
    if (!Array.isArray(guilds) || !r) return back(res, st.linkId, 'err');
    if (guilds.some(g => g.id === r.target_id)) { await markVerified(st.viewer, r.id, 'discord'); return back(res, st.linkId, 'ok'); }
    back(res, st.linkId, 'fail');
  } catch (e) { back(res, st.linkId, 'err'); }
}));

