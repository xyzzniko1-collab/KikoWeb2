/* signed OAuth state (stateless -> aman untuk serverless) */
function signState(o) {
  if (!process.env.SESSION_SECRET) throw cfgErr('SESSION_SECRET');
  const p = Buffer.from(JSON.stringify(o)).toString('base64url');
  return p + '.' + crypto.createHmac('sha256', process.env.SESSION_SECRET).update(p).digest('base64url');
}
function readState(t, kind, viewer) {
  try {
    const [p, s] = String(t).split('.');
    const e = crypto.createHmac('sha256', process.env.SESSION_SECRET).update(p).digest('base64url');
    if (s.length !== e.length || !crypto.timingSafeEqual(Buffer.from(s), Buffer.from(e))) return null;
    const o = JSON.parse(Buffer.from(p, 'base64url').toString());
    return (o.exp > Date.now() && o.kind === kind && o.viewer === viewer) ? o : null;
  } catch (e) { return null; }
}

/* Supabase Storage */
let sb, bucketReady;
async function storage() {
  if (!process.env.SUPABASE_URL) throw cfgErr('SUPABASE_URL');
  if (!process.env.SUPABASE_SERVICE_ROLE_KEY) throw cfgErr('SUPABASE_SERVICE_ROLE_KEY');
  if (!sb) sb = createClient(process.env.SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY, { auth: { persistSession: false } });
  if (!bucketReady) { await sb.storage.createBucket(BUCKET, { public: false }).catch(() => {}); bucketReady = true; }
  return sb.storage.from(BUCKET);
}

