let pool;
function P() {
  if (!pool) {
    const url = process.env.DATABASE_URL; if (!url) throw cfgErr('DATABASE_URL');
    pool = new Pool({ connectionString: url, ssl: /localhost|127\.0\.0\.1/.test(url) ? false : { rejectUnauthorized: false }, max: 1, idleTimeoutMillis: 10000 });
  }
  return pool;
}
const q = async (sql, params = []) => (await P().query(sql, params)).rows;
const q1 = async (sql, params) => (await q(sql, params))[0] || null;
async function tx(fn) {
  const c = await P().connect();
  try {
    await c.query('BEGIN');
    const r = await fn((s, p = []) => c.query(s, p).then(x => x.rows));
    await c.query('COMMIT');
    return r;
  } catch (e) { try { await c.query('ROLLBACK'); } catch (_) {} throw e; }
  finally { c.release(); }
}

