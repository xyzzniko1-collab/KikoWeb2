const progressOf = (req, linkId) => q1(
  `SELECT (SELECT COUNT(*) FROM reqs WHERE link_id=$1)::int total,
          (SELECT COUNT(*) FROM reqs r JOIN verifs v ON v.req_id=r.id AND v.viewer=$2 WHERE r.link_id=$1)::int done`, [linkId, req.viewer]);
function modeOf(r) {
  if (r.platform === 'discord' && r.target_id && DISCORD_OK) return 'discord';
  if (r.platform === 'youtube' && r.target_id && GOOGLE_OK) return 'youtube';
  return 'timer';
}

