function parseLinkBody(b) {
  const out = {
    title: clean(b.title, 140), descr: clean(b.desc, 600), type: b.type === 'url' ? 'url' : 'file',
    access: b.access === 'member' ? 'member' : 'all', url: clean(b.url, 1000), announce: !!b.announce, reqs: [], file: null
  };
  if (!out.title) return { error: 'Judul wajib diisi' };
  if (out.type === 'url' && !okUrl(out.url)) return { error: 'URL download tidak valid' };
  if (b.file && out.type === 'file') {
    if (!/^[a-f0-9]{32}$/.test(String(b.file.key))) return { error: 'Data file tidak valid' };
    out.file = { key: b.file.key, name: safeName(b.file.name), size: Math.max(0, Math.min(Number(b.file.size) || 0, 2e9)) };
  }
  for (const r of (Array.isArray(b.reqs) ? b.reqs : []).slice(0, 12)) {
    const item = { id: num(r.id) || null, platform: PLATFORMS.includes(r.platform) ? r.platform : 'other', label: clean(r.label, 100), url: clean(r.url, 1000), target_id: clean(r.target_id, 100) };
    if (!okUrl(item.url)) return { error: 'URL tugas harus diawali https://' };
    out.reqs.push(item);
  }
  return { d: out };
}
async function saveReqs(t, linkId, reqs) {
  const ex = new Map((await t('SELECT * FROM reqs WHERE link_id=$1', [linkId])).map(x => [x.id, x]));
  const keep = new Set(); let sort = 0;
  for (const r of reqs) {
    const old = r.id && ex.get(r.id);
    if (old) {
      await t('UPDATE reqs SET platform=$1,label=$2,url=$3,target_id=$4,sort=$5 WHERE id=$6', [r.platform, r.label, r.url, r.target_id, sort++, r.id]);
      if (old.platform !== r.platform || old.target_id !== r.target_id) await t('DELETE FROM verifs WHERE req_id=$1', [r.id]);
      keep.add(r.id);
    } else {
      const [row] = await t('INSERT INTO reqs(link_id,platform,label,url,target_id,sort) VALUES($1,$2,$3,$4,$5,$6) RETURNING id', [linkId, r.platform, r.label, r.url, r.target_id, sort++]);
      keep.add(row.id);
    }
  }
  for (const id of ex.keys()) if (!keep.has(id)) await t('DELETE FROM reqs WHERE id=$1', [id]);
}
