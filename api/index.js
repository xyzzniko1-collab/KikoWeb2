app.post('/api/links/:id/download', H(async (req, res) => {
  const l = await q1('SELECT * FROM links WHERE id=$1', [num(req.params.id)]);
  if (!l) return res.status(404).json({ error: 'Tidak ditemukan' });
  if (!canSee(req, l)) return res.status(403).json({ error: 'Khusus member' });
  const p = await progressOf(req, l.id);
  if (p.done < p.total) return res.status(403).json({ error: 'Selesaikan semua tugas dulu' });
  if (l.type === 'url') {
    await q('UPDATE links SET downloads=downloads+1 WHERE id=$1', [l.id]);
    return res.json({ url: l.url, external: true });
  }
  const s = await storage();
  const { data, error } = await s.createSignedUrl(l.file_key, 60, { download: l.file_name });
  if (error || !data) return res.status(500).json({ error: 'File tidak ditemukan di penyimpanan' });
  await q('UPDATE links SET downloads=downloads+1 WHERE id=$1', [l.id]);
  res.json({ url: data.signedUrl });
}));

